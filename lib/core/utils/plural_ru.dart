// Склонение по числу: «1 трек», «2 трека», «5 треков», «21 трек».
//
// Везде в приложении писалось «${n} треков», и на карточке плейлиста из
// 21 трека получалось «21 треков» (отзыв Orion 2026-09-27). Локализации в
// проекте нет, строки русские — значит и склонять надо самим.

/// Форма слова по числу [count]: [one] — «трек», [few] — «трека»,
/// [many] — «треков».
String pluralRu(int count, String one, String few, String many) {
  final n = count.abs();
  // 11–14 всегда «треков», даже когда заканчиваются на 1, 2, 3
  if (n % 100 >= 11 && n % 100 <= 14) return many;
  return switch (n % 10) {
    1 => one,
    2 || 3 || 4 => few,
    _ => many,
  };
}

/// «21 трек», «2 трека», «5 треков».
String trackCountLabel(int count) =>
    '$count ${pluralRu(count, 'трек', 'трека', 'треков')}';
