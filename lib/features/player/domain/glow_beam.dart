// lib/features/player/domain/glow_beam.dart
//
// «Луч» караоке: насколько близко голос к этому слогу **прямо сейчас**.
//
// Зачем это отдельно от свечения. Свечение (`GlowValues.glow`) у спетого
// слога остаётся единицей до конца строки — так и задумано, спетый текст
// должен стоять ярким. Но вместе с яркостью у него оставался и ореол, а
// ореол — это тень текста, то есть **ещё одна отрисовка всех глифов с
// размытием**, и стоит она дороже самой буквы.
//
// Замер на Pixel 7 (профильная сборка, караоке по слогам, «Never Gonna Give
// You Up», окно 60 с):
//
//   как было (ореол у каждого спетого слога)      растр 15,6 мс  ~36 кадр/с
//   ореол только у слогов на переходе             растр  7,7 мс  ~75 кадр/с
//   совсем без ореола                             растр  7,1 мс  ~82 кадр/с
//
// То есть ореол у спетых слогов съедал больше половины кадра, а на телефоне
// втрое медленнее (Tecno Pova 5 у Elian) — и вовсе весь бюджет. Проверено
// отдельно, что дело именно в количестве светящихся слогов: и порог по
// свечению, и постоянный радиус размытия не дали ничего, а ограничение
// «только слоги на переходе» дало сразу вдвое.
//
// Поэтому ореол теперь едет вместе с голосом: зажигается чуть раньше слога и
// гаснет вскоре после него. Яркость самих букв не изменилась.

/// За сколько миллисекунд до начала слога ореол начинает разгораться.
const kBeamLeadMs = 140.0;

/// За сколько миллисекунд после конца слога ореол гаснет.
const kBeamTailMs = 420.0;

/// Сила луча на слоге `[startMs, endMs]` в момент [ms]: 0 — голос далеко,
/// 1 — поётся прямо сейчас. Нарастает за [kBeamLeadMs] до начала и спадает за
/// [kBeamTailMs] после конца, так что порога не видно.
double beamAt(double ms, double startMs, double endMs) {
  if (ms < startMs) {
    final lead = (startMs - ms) / kBeamLeadMs;
    return lead >= 1.0 ? 0.0 : 1.0 - lead;
  }
  if (ms <= endMs) return 1.0;
  final tail = (ms - endMs) / kBeamTailMs;
  return tail >= 1.0 ? 0.0 : 1.0 - tail;
}
