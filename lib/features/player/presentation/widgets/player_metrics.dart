// Насколько крупнее элементы управления на странице трека.
//
// Просил Elian (2026-09-27): кнопки плеера мелковаты. Решение Orion — **одним
// значением для всех**, без ползунка в настройках, поэтому здесь одно число, и
// все размеры кнопок на странице трека проходят через `pscale`.
//
// Что масштабируется: ряд управления (перемешивание, назад, пауза, вперёд,
// повтор), кнопки у названия (избранное, в плейлист), капсулы внизу («Текст»,
// «Добавить», «Таймер») и кнопки верхней панели. Обложка под это число не
// попадает — она считается от свободного места (`_CompactLayout`).
//
// Менять размер — только здесь, но помнить: **ряду управления нужна ширина.**
// Он раздаёт место через `spaceEvenly` и ужимается сам, если не влезает
// (`_Controls`), так что поднимать число без свободной ширины бесполезно —
// именно на этом первая попытка и провалилась. Проверять на трёх ширинах:
// телефон, разложенный Fold и ПК.

/// Множитель размеров кнопок плеера. 1.0 — как было до 2026-09-27.
///
/// Первая попытка была 1.25, и на телефоне её не было видно: ряд управления
/// сидел в `FittedBox(scaleDown)`, не влезал по ширине и ужимался обратно
/// (кнопка паузы 65 приезжала как 54). Сначала убрали сжатие
/// (`_Controls` раздаёт ширину сам), и только потом число начало работать.
const kPlayerControlScale = 1.4;

/// Размер [value] с учётом [kPlayerControlScale].
double pscale(double value) => value * kPlayerControlScale;
